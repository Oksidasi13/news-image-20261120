def draw_story_card(draw, left, top, right, bottom, story):
    accent = story["color"]
    draw.rounded_rectangle(
        (left, top, right, bottom),
        radius=8,
        fill=PALETTE["card"],
        outline=PALETTE["card_edge"],
        width=1,
    )
    # Accent bar across the top; the square lower half hides the
    # rounded bottom corners of the bar so only the top stays round.
    draw.rounded_rectangle((left, top, right, top + 16), radius=8, fill=accent)
    draw.rectangle((left, top + 8, right, top + 16), fill=accent)
    # Pictogram disc, then the kicker beside it.
    disc_x, disc_y = left + 52, top + 62
    draw.ellipse(
        (disc_x - 33, disc_y - 33, disc_x + 33, disc_y + 33), fill=accent
    )
    GLYPHS[story["glyph"]](draw, disc_x, disc_y)
    draw.text((left + 98, top + 52), story["kicker"], font=KICKER_FONT, fill=accent)
    # Headline, then body, both wrapped to the card's inner width.
    text_width = right - left - 40
    y = top + 104
    for line in wrap_text(draw, story["headline"], HEAD_FONT, text_width):
        draw.text((left + 20, y), line, font=HEAD_FONT, fill=PALETTE["ink"])
        y += 36
    y += 6
    for line in wrap_text(draw, story["body"], BODY_FONT, text_width):
        draw.text((left + 20, y), line, font=BODY_FONT, fill=PALETTE["body"])
        y += 27


def build_image():
    img = Image.new("RGB", (SIZE, SIZE), PALETTE["paper"])
    draw = ImageDraw.Draw(img)

    # Header band.
    draw.rectangle((0, 0, SIZE, 118), fill=PALETTE["navy"])
    draw.text((24, 16), "FRIDAY 20 NOVEMBER 2026", font=DATE_FONT, fill=PALETTE["white"])
    draw.text(
        (24, 78),
        "THE WORLD IN ONE IMAGE  \u2022  SIX STORIES FROM ONE DAY",
        font=SUB_FONT,
        fill=PALETTE["muted"],
    )
    draw.rectangle((0, 118, SIZE, 124), fill=PALETTE["rule"])

    # Six cards in a 2-by-3 grid.
    margin = 16
    gap = 16
    grid_top = 140
    grid_bottom = 968
    cell_w = (SIZE - 2 * margin - gap) // 2
    cell_h = (grid_bottom - grid_top - 2 * gap) // 3
    for index, story in enumerate(STORIES):
        col, row = index % 2, index // 2
        x0 = margin + col * (cell_w + gap)
        y0 = grid_top + row * (cell_h + gap)
        draw_story_card(draw, x0, y0, x0 + cell_w, y0 + cell_h, story)

    # Footer band.
    draw.rectangle((0, 968, SIZE, SIZE), fill=PALETTE["navy"])
    draw.text(
        (24, 976),
        "Friday\u2019s news as reported on 20 November 2026  \u2022  "
        "Sources: Reuters, BBC, The Hindu, AP, Sensor Tower, PTI",
        font=FOOT_FONT,
        fill=PALETTE["muted"],
    )
    draw.text(
        (24, 998),
        "Figures are as reported that day; claims that could not be "
        "confirmed are not stated as fact.",
        font=FOOT_FONT,
        fill=PALETTE["muted"],
    )
    return img


def main():
    target = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
        os.path.dirname(os.path.abspath(__file__)), "entry.png"
    )
    build_image().save(target, optimize=True)
    print("wrote", target, os.path.getsize(target), "bytes")


if __name__ == "__main__":
    main()

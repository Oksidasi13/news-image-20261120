#!/usr/bin/env python3
"""Hand-draw the news-image-20261120 infographic with PIL.

The result is a 1024x1024 newspaper-style image: a navy header with
the date, then six story cards in a 2-by-3 grid, each with a coloured
pictogram disc, a kicker, a headline and a short body. Nothing is
generated by a model and nothing is fetched: every mark on the page
comes from PIL drawing calls (rectangles, ellipses, arcs, polygons,
text) in DejaVu fonts, so the same script always writes the same
bytes.

The stories are Friday 20 November 2026's news. The picture was
first drawn early that morning, then redrawn on Friday night once
the day's two moving stories had settled: Cyclone Akvan had come
ashore in the morning and weakened, and the COP31 draft had dropped
its fossil-fuel wording and its $120bn adaptation goal without a
final deal. The GTA 6 launch-day figure was also refreshed to
Sensor Tower's end-of-day estimate, and the other three stories
were checked again against fresh sources and left as written.

Usage: python3 draw.py [output-path]   (default: entry.png beside this file)
"""

import os
import sys

from PIL import Image, ImageDraw, ImageFont

SIZE = 1024

PALETTE = {
    "paper": (246, 241, 231),
    "navy": (29, 43, 74),
    "rule": (192, 57, 43),
    "card": (255, 253, 248),
    "card_edge": (216, 205, 184),
    "ink": (43, 43, 43),
    "body": (51, 48, 42),
    "muted": (200, 208, 224),
    "white": (255, 255, 255),
}

FONT_FOLDER = "/usr/share/fonts/truetype/dejavu"


def load_font(filename, size):
    return ImageFont.truetype(os.path.join(FONT_FOLDER, filename), size)


DATE_FONT = load_font("DejaVuSans-Bold.ttf", 54)
SUB_FONT = load_font("DejaVuSans-Bold.ttf", 24)
KICKER_FONT = load_font("DejaVuSans-Bold.ttf", 20)
HEAD_FONT = load_font("DejaVuSans-Bold.ttf", 30)
BODY_FONT = load_font("DejaVuSans.ttf", 20)
FOOT_FONT = load_font("DejaVuSans.ttf", 17)


def wrap_text(canvas, text, font, max_width):
    """Split `text` into lines no wider than `max_width` pixels.

    Greedy: words are added to the current line while they fit; a word
    that would overflow starts the next line instead.
    """
    lines = []
    current = ""
    for word in text.split():
        candidate = word if current == "" else current + " " + word
        if canvas.textlength(candidate, font=font) <= max_width:
            current = candidate
        else:
            if current:
                lines.append(current)
            current = word
    if current:
        lines.append(current)
    return lines


def glyph_clock(draw, cx, cy):
    white = PALETTE["white"]
    draw.ellipse((cx - 18, cy - 18, cx + 18, cy + 18), outline=white, width=3)
    for tip_x, tip_y in ((cx, cy - 11), (cx + 9, cy + 5)):
        draw.line((cx, cy, tip_x, tip_y), fill=white, width=3)
    draw.ellipse((cx - 3, cy - 3, cx + 3, cy + 3), fill=white)


def glyph_spiral(draw, cx, cy):
    white = PALETTE["white"]
    arcs = ((20, 20, 320), (15, 110, 60), (10, 200, 150), (5, 290, 240))
    for radius, start, end in arcs:
        draw.arc(
            (cx - radius, cy - radius, cx + radius, cy + radius),
            start,
            end,
            fill=white,
            width=3,
        )
    draw.ellipse((cx - 2, cy - 2, cx + 2, cy + 2), fill=white)


def glyph_scales(draw, cx, cy):
    white = PALETTE["white"]
    draw.line((cx, cy - 18, cx, cy + 16), fill=white, width=3)
    draw.line((cx - 17, cy - 14, cx + 17, cy - 14), fill=white, width=3)
    draw.line((cx, cy + 16, cx - 8, cy + 16), fill=white, width=3)
    draw.line((cx, cy + 16, cx + 8, cy + 16), fill=white, width=3)
    for pan_x in (cx - 17, cx + 17):
        draw.line((pan_x, cy - 14, pan_x - 6, cy + 2), fill=white, width=2)
        draw.line((pan_x, cy - 14, pan_x + 6, cy + 2), fill=white, width=2)
        draw.polygon(
            ((pan_x - 9, cy + 2), (pan_x + 9, cy + 2), (pan_x, cy + 12)),
            fill=white,
        )


def glyph_globe(draw, cx, cy):
    white = PALETTE["white"]
    draw.ellipse((cx - 18, cy - 18, cx + 18, cy + 18), outline=white, width=3)
    draw.arc((cx - 8, cy - 18, cx + 8, cy + 18), 0, 360, fill=white, width=2)
    draw.line((cx - 18, cy, cx + 18, cy), fill=white, width=2)


def glyph_probe(draw, cx, cy):
    white = PALETTE["white"]
    star = [(0, -18), (5, -5), (18, 0), (5, 5), (0, 18), (-5, 5), (-18, 0), (-5, -5)]
    draw.polygon([(cx + dx, cy + dy) for dx, dy in star], fill=white)
    draw.arc((cx - 23, cy - 9, cx + 23, cy + 9), 195, 345, fill=white, width=2)


def glyph_pad(draw, cx, cy):
    white = PALETTE["white"]
    draw.rounded_rectangle(
        (cx - 20, cy - 9, cx + 20, cy + 13), radius=6, outline=white, width=3
    )
    draw.rectangle((cx - 13, cy - 2, cx - 5, cy + 2), fill=white)
    draw.rectangle((cx - 11, cy - 4, cx - 7, cy + 4), fill=white)
    draw.ellipse((cx + 7, cy - 4, cx + 11, cy), fill=white)
    draw.ellipse((cx + 13, cy + 2, cx + 17, cy + 6), fill=white)


GLYPHS = {
    "clock": glyph_clock,
    "spiral": glyph_spiral,
    "scales": glyph_scales,
    "globe": glyph_globe,
    "probe": glyph_probe,
    "pad": glyph_pad,
}

